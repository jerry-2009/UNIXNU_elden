"""Verify Elden stock PHY facts against pinned SM8750 Linux and emit the table."""
import argparse,hashlib,json,re,struct,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
REV='6f97250ead155fc3b980856323e99a4623dae73d'
sys.path.insert(0,str(ROOT/'tools/legacy-workbench'))
from fdt_memory_plan import parse_fdt
def digest(b):return hashlib.sha256(b).hexdigest()
def prepare(facts,repo,out,stock=None):
    if out.exists():raise ValueError('New output required')
    f=json.loads(facts.read_text(encoding='utf-8'))
    assert f['schema']==1 and f['device']=='TB322FC' and f['soc']=='SM8750'
    seq=f['phy_sequence'];assert len(seq)==127 and all(len(v)==3 for v in seq)
    assert seq[0]==[0x440,3,0] and seq[-2:]==[[0x400,0,0],[0x444,3,0]]
    assert all(0<=o<0x2000 and o%4==0 and 0<=v<=255 and d==0 for o,v,d in seq)
    if stock:
        data=stock.read_bytes();assert digest(data)==f['stock_fdt_sha256']
        nodes,_=parse_fdt(data);props=nodes[f['node']]
        words=struct.unpack('>'+str(len(props['qcom,phy-sequence'])//4)+'I',props['qcom,phy-sequence'])
        assert [list(words[i:i+3]) for i in range(0,len(words),3)]==seq
        names=props['reg-names'].decode().rstrip('\0').split('\0')
        words=struct.unpack('>'+str(len(props['reg'])//4)+'I',props['reg'])
        assert dict(zip(names,[list(words[i:i+2]) for i in range(0,len(words),2)]))==f['windows']
    inputs={}
    def source(p):
        b=subprocess.check_output(['git','-C',str(repo),'show',REV+':'+p]);inputs[p]=digest(b);return b.decode()
    prefix='drivers/phy/qualcomm/'
    code=source(prefix+'phy-qcom-qmp-pcie.c')
    headers=['phy-qcom-qmp-qserdes-com-v7.h','phy-qcom-qmp-qserdes-txrx-v7.h','phy-qcom-qmp-pcs-v7.h','phy-qcom-qmp-pcs-pcie-v6.h']
    defines={}
    for name in headers:
        for k,v in re.findall(r'^#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)(?=\s|$)',source(prefix+name),re.M):
            value=int(v,0)
            if k in defines:assert defines[k]==value
            defines[k]=value
    offsets=dict((k,int(v,0)) for k,v in re.findall(r'\.(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)',code.split('qmp_pcie_offsets_v7 = {',1)[1].split('};',1)[0]))
    assert offsets=={'serdes':0,'pcs':0x400,'pcs_misc':0x800,'tx':0x1000,'rx':0x1200,'tx2':0x1800,'rx2':0x1a00}
    cfg=code.split('sm8750_qmp_gen3x2_pciephy_cfg = {',1)[1].split('\n};',1)[0]
    assert re.search(r'\.lanes\s*=\s*2',cfg) and '&qmp_pcie_offsets_v7' in cfg and 'pciephy_v7_regs_layout' in cfg
    linux={};symbol={}
    for block in ['serdes','tx','rx','pcs','pcs_misc']:
        name='sm8750_qmp_gen3x2_pcie_'+block+'_tbl'
        assert '.'+block in cfg and name in cfg
        text=code.split(name+'[] = {',1)[1].split('};',1)[0]
        entries=re.findall(r'QMP_PHY_INIT_CFG\(\s*(\w+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*\)',text)
        assert entries and len(entries)==text.count('QMP_PHY_INIT_CFG(')
        for key,v in entries:
            assert key in defines
            for target in [block]+([block+'2'] if block in ['tx','rx'] else []):
                address=offsets[target]+defines[key];assert address not in linux
                linux[address]=int(v,0);symbol[address]=key
    stock_values={o:v for o,v,_ in seq[1:-2]};assert len(stock_values)==len(seq)-3
    changed=[{'offset':hex(o),'register':symbol[o],'linux':linux[o],'stock':stock_values[o]} for o in sorted(linux.keys()&stock_values.keys()) if linux[o]!=stock_values[o]]
    missing=[{'offset':hex(o),'register':symbol[o],'linux':linux[o]} for o in sorted(linux.keys()-stock_values.keys())]
    extra=[{'offset':hex(o),'stock':stock_values[o]} for o in sorted(stock_values.keys()-linux.keys())]
    out.mkdir(parents=True)
    text='/* SPDX-License-Identifier: GPL-2.0-only */\n/* Generated by tools/prepare_pcie_phy.py; TB322FC stock, not a generic SM8750 table. */\n'
    text+='static const EldenPciePhyWrite elden_pcie_phy_sequence[] = {\n'
    text+=''.join('    {0x%04x,0x%02x,%u},\n'%tuple(v) for v in seq)
    text+='};\n'
    (out/'PhySequence.inc').write_text(text,encoding='utf-8',newline='\n')
    report={'revision':REV,'source_inputs':inputs,'facts_sha256':digest(facts.read_bytes()),'stock_fdt_sha256':f['stock_fdt_sha256'],
            'stock_fdt_checked':bool(stock),'sequence_count':len(seq),'output_sha256':digest(text.encode()),'linux_register_count':len(linux),
            'linux_value_differences':changed,'linux_only':missing,'stock_only':extra,'hardware_operations':False}
    (out/'result.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    return report
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--linux-repository',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    p.add_argument('--facts',type=Path,default=ROOT/'drivers/EldenPcie/board-facts.json');p.add_argument('--stock-fdt',type=Path)
    a=p.parse_args();r=prepare(a.facts,a.linux_repository,a.output,a.stock_fdt);print(json.dumps(r))
if __name__=='__main__':main()
